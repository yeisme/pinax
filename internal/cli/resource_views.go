// Resource aliases derive from the registered tree and share the owner's handler.
func registerResourceViews(root *cobra.Command, ctx commandBuildContext) {
	if root.Name() == "list" && root.Flags().Lookup("all") == nil {
		root.Flags().Bool("all", false, "Show every matching row in human output")
	}
	for _, child := range root.Commands() {
		registerResourceViews(child, ctx)
	}
	var show *cobra.Command
	for _, child := range root.Commands() {
		if child.Name() == "show" && !child.HasSubCommands() {
			show = child
			break
		}
	}
	if show == nil {
		return
	}
	show.Hidden = true
	verbs := []string{"describe"}
	if strings.Count(show.Use, "<") == 1 {
		verbs = append(verbs, "get")
	}
	for _, verb := range verbs {
		exists := false
		for _, child := range root.Commands() {
			if child.Name() == verb {
				exists = true
			}
		}
		if exists {
			continue
		}
		cmd := &cobra.Command{Use: verb + strings.TrimPrefix(show.Use, "show"), Short: strings.ReplaceAll(show.Short, "Show", "Read"), Annotations: map[string]string{"resource.legacy": strings.TrimPrefix(show.CommandPath(), "pinax ")}, RunE: show.RunE, Run: show.Run, PreRunE: show.PreRunE, PostRunE: show.PostRunE}
		cmd.Flags().AddFlagSet(show.LocalNonPersistentFlags())
		cmd.Args = func(cmd *cobra.Command, args []string) error {
			n := strings.Count(show.Use, "<")
			if n > 0 && len(args) != n {
				code := "missing_argument"
				if len(args) > n {
					code = "unexpected_argument"
				}
				next := root.CommandPath() + " --help"
				for _, child := range root.Commands() {
					if child.Name() == "list" {
						next = root.CommandPath() + " list"
						break
					}
				}
				next = resourceScopedCommand(cmd, next)
				e := &domain.CommandError{Code: code, Field: "resource-id", Message: "Supply the resource identity shown by list", Hint: next}
				p := domain.NewErrorProjection(strings.ReplaceAll(strings.TrimPrefix(cmd.CommandPath(), "pinax "), " ", "."), e)
				p.Actions = []domain.Action{{Name: "discover", Command: next}}
				return ctx.renderProjection(cmd, p, e)
			}
			if show.Args != nil {
				return show.Args(cmd, args)
			}
			return nil
		}
		cmd.ValidArgsFunction = boundedResourceCompletion(show.ValidArgsFunction)
		root.AddCommand(cmd)
	}
}

func boundedResourceCompletion(query func(*cobra.Command, []string, string) ([]string, cobra.ShellCompDirective)) func(*cobra.Command, []string, string) ([]string, cobra.ShellCompDirective) {
	return func(cmd *cobra.Command, args []string, prefix string) ([]string, cobra.ShellCompDirective) {
		if query == nil || strings.Contains(cmd.CommandPath(), "backend") {
			return nil, cobra.ShellCompDirectiveNoFileComp
		}
		done := make(chan []string, 1)
		go func() {
			rows, _ := query(cmd, args, prefix)
			sort.Strings(rows)
			if len(rows) > 50 {
				rows = rows[:50]
			}
			done <- rows
		}()
		select {
		case rows := <-done:
			return rows, cobra.ShellCompDirectiveNoFileComp
		case <-time.After(250 * time.Millisecond):
			return nil, cobra.ShellCompDirectiveNoFileComp
		}
	}
}

func resourceProjection(cmd *cobra.Command, p domain.Projection) domain.Projection {
	p.AllRows, _ = cmd.Flags().GetBool("all")
	if strings.HasSuffix(p.Command, ".list") && p.Error == nil {
		if p.Facts == nil {
			p.Facts = map[string]string{}
		}
		kind := strings.TrimSuffix(p.Command, ".list")
		kind = strings.ReplaceAll(kind, ".", "_")
		// Owner services already publish 1-based <kind>.N.id facts. Filling the
		// same keys from the first JSON array is 0-based and overwrites row 1
		// with the last row, so only synthesize identities that are absent.
		if _, exists := p.Facts[kind+".1.id"]; !exists {
			rows := resourceListRows(p.Data)
			if len(rows) > 0 {
				if _, counted := p.Facts["result_count"]; !counted {
					p.Facts["result_count"] = fmt.Sprint(len(rows))
				}
				for i, row := range rows {
					fields := []string{"id", "ref", "name"}
					if kind == "project" {
						fields = []string{"slug"}
					}
					for _, field := range fields {
						if id, ok := row[field].(string); ok && id != "" {
							p.Facts[fmt.Sprintf("%s.%d.id", kind, i+1)] = id
							break
						}
					}
				}
			}
		}
	}

	if cmd.Annotations["resource.legacy"] != "" {
		p.Command = strings.ReplaceAll(strings.TrimPrefix(cmd.CommandPath(), "pinax "), " ", ".")
		if cmd.Name() == "get" && p.Error == nil {
			p.Data = identityResource(p.Data)
			facts := map[string]string{}
			for k, v := range p.Facts {
				if identityKey(k) {
					facts[k] = v
				}
			}
			p.Facts = facts
			p.Actions = []domain.Action{{Name: "next", Command: resourceScopedCommand(cmd, cmd.Parent().CommandPath()+" --help")}}
		}
	}
	// Actions are generated by the owner; only registered compatibility paths change.
	var visit func(*cobra.Command)
	visit = func(node *cobra.Command) {
		if node.Name() == "describe" && node.Annotations["resource.legacy"] != "" {
			old := "pinax " + node.Annotations["resource.legacy"]
			for i := range p.Actions {
				if p.Actions[i].Command == old || strings.HasPrefix(p.Actions[i].Command, old+" ") {
					p.Actions[i].Command = node.CommandPath() + strings.TrimPrefix(p.Actions[i].Command, old)
				}
			}
		}
		for _, child := range node.Commands() {
			visit(child)
		}
	}
	visit(cmd.Root())
	return p
}

func resourceListRows(data any) []map[string]any {
	raw, err := json.Marshal(data)
	if err != nil {
		return nil
	}
	var decoded map[string]any
	if json.Unmarshal(raw, &decoded) != nil {
		return nil
	}
	keys := make([]string, 0, len(decoded))
	for key := range decoded {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		switch values := decoded[key].(type) {
		case []any:
			rows := make([]map[string]any, 0, len(values))
			for _, value := range values {
				row, ok := value.(map[string]any)
				if !ok {
					return nil
				}
				rows = append(rows, row)
			}
			if len(rows) > 0 {
				return rows
			}
		}
	}
	return nil
}

func identityKey(k string) bool {
	return k == "slug" || k == "id" || k == "ref" || k == "name" || k == "title" || k == "status" || k == "kind" || k == "revision" || strings.HasSuffix(k, "_id") || strings.HasSuffix(k, "_ref")
}
func identityResource(v any) any {
	raw, err := json.Marshal(v)
	if err != nil {
		return nil
	}
	var source map[string]any
	if json.Unmarshal(raw, &source) != nil {
		return nil
	}
	out := map[string]any{}
	for k, value := range source {
		if nested, ok := value.(map[string]any); ok {
			if safe := identityResource(nested).(map[string]any); len(safe) > 0 {
				out[k] = safe
			}
		} else if identityKey(k) {
			switch value.(type) {
			case string, float64, bool:
				out[k] = value
			}
		}
	}
	return out
}

func ExitCode(err error) int {
	if err == nil {
		return 0
	}
	var e *domain.CommandError
	if errors.As(err, &e) && (e.Code == "foreign_completion_file" || e.Code == "invalid_shell" || e.Code == "confirmation_required" || e.Code == "missing_argument" || e.Code == "unexpected_argument" || strings.Contains(e.Code, "not_found") || strings.HasPrefix(e.Code, "unknown_")) {
		return 2
	}
	return 1
}

func resourceScopedCommand(cmd *cobra.Command, command string) string {
	for _, name := range []string{"vault", "config", "backend", "remote"} {
		if f := cmd.Flags().Lookup(name); f != nil && f.Changed {
			command += " --" + name + " '" + strings.ReplaceAll(f.Value.String(), "'", "'\"'\"'") + "'"
		}
	}
	return command
}
